def _fuzzy_find(query: str, country_list: list[dict]) -> dict | None:
    """Return the closest country by name using difflib, or None if no good match."""
    import difflib

    names = [str(c.get("name", "")).lower() for c in country_list]
    matches = difflib.get_close_matches(query, names, n=1, cutoff=0.6)
    if not matches:
        return None
    return next((c for c in country_list if str(c.get("name", "")).lower() == matches[0]), None)


def find_country(query: str, country_list: list[dict]) -> dict | None:
    """Find a country by code or name (case-insensitive, Dutch or English).

    Matching priority:
      1. Exact code match  (e.g. "NL", "CH")
      2. Exact name match or Dutch alias  (e.g. "Netherlands", "Nederland")
      3. Name starts-with
      4. Fuzzy match via difflib (handles typos)
    """
    q = query.strip().lower()
    # Resolve Dutch aliases and common alternatives
    q = _COUNTRY_ALIASES.get(q, q)

    hit = next((c for c in country_list if str(c.get("code", "")).lower() == q), None)
    if hit:
        return hit
    hit = next((c for c in country_list if str(c.get("name", "")).lower() == q), None)
    if hit:
        return hit
    hit = next((c for c in country_list if str(c.get("name", "")).lower().startswith(q)), None)
    if hit:
        return hit
    return _fuzzy_find(q, country_list)


def country_id(country: dict) -> str:
    """Return the best available ID for a country dict."""
    return str(
        country.get("_id")
        or country.get("id")
        or country.get("countryId")
        or country.get("code")
    )
